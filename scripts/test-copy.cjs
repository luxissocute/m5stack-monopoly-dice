const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const root = require('node:path').resolve(__dirname, '..');
const req = createRequire(root + '/package.json');
const { _electron } = createRequire(req.resolve('@playwright/test'))('playwright');
(async () => {
  const env = {...process.env}; delete env.ELECTRON_RUN_AS_NODE;
  const app = await _electron.launch({executablePath:process.argv[2] || req('electron'), args:process.argv[2]?[]:[root],cwd:root,env});
  let original;
  try {
    original = await app.evaluate(({clipboard}) => clipboard.readText());
    const page=await app.firstWindow();
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    await page.locator('#mode-single').waitFor();
    await page.screenshot({path:root+'/artifacts/setup-modes-1.0.1.png'});
    await page.locator('#mode-single').click();
    assert.equal(await page.locator('#human-count').isVisible(),false);
    await page.locator('#player-name').fill('保留設定');
    await page.locator('#offline-back').click();
    await page.locator('#mode-single').click();
    assert.equal(await page.locator('#player-name').inputValue(),'保留設定');
    const backStyle=await page.locator('#offline-back').evaluate(el=>({border:getComputedStyle(el).borderTopStyle,height:el.getBoundingClientRect().height}));
    assert.notEqual(backStyle.border,'none'); assert.ok(backStyle.height>=44);
    await page.screenshot({path:root+'/artifacts/setup-back-1.0.1.png'});
    await page.locator('#offline-back').click();
    await page.locator('#mode-multi').click();
    await page.locator('#mode-local').click();
    assert.equal(await page.locator('#human-count').inputValue(),'2');
    await page.locator('#offline-back').click();
    await page.locator('#lobby-room').click();
    await page.locator('#online-join').click();
    assert.equal(await page.locator('#room-seats').isVisible(),false);
    await page.locator('#room-name').fill('連線名字保留');
    await page.locator('#room-setup-back').click();
    await page.locator('#online-create').click();
    assert.equal(await page.locator('#room-name').inputValue(),'連線名字保留');
    assert.equal(await page.locator('#room-code').isVisible(),false);
    await page.locator('#host-start').click();
    await page.locator('#host-link').waitFor({timeout:120000});
    const host = await page.locator('#host-link').inputValue();
    await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', {configurable:true,value:{writeText:async()=>{throw new Error('Browser clipboard blocked');}}}); });
    await page.locator('#host-copy').click();
    await page.waitForFunction(() => document.querySelector('#toast')?.textContent?.includes('已複製主機入口'));
    assert.equal(await app.evaluate(({clipboard})=>clipboard.readText()),host);
    await page.locator('#room-name').fill('複製測試');
    await page.locator('#room-submit').click();
    await page.locator('#invite-link').waitFor();
    await page.locator('#copy-code').click();
    await page.waitForFunction(() => document.querySelector('#toast')?.textContent?.includes('已複製房間邀請連結'));
    const invite=await page.locator('#invite-link').inputValue();
    assert.equal(await app.evaluate(({clipboard})=>clipboard.readText()),invite);
    assert.ok(new URL(invite).searchParams.get('room'));
    assert.equal(new URL(invite).searchParams.get('access'),new URL(host).searchParams.get('access'));
    const positions=await page.evaluate(()=>({invite:document.querySelector('#invite-link').getBoundingClientRect().top,host:document.querySelector('#host-panel').getBoundingClientRect().top}));
    assert.ok(positions.invite<positions.host,'Room invitation must be first');
    await page.screenshot({path:root+'/artifacts/clipboard-1.0.1.png',fullPage:true});
    assert.deepEqual(errors,[]);
    const win=await app.browserWindow(page);
    await app.evaluate(({dialog})=>{dialog.showMessageBox=async(_window,options)=>{dialog.__lastCloseOptions=options;return {response:2};};});
    await win.evaluate(w=>w.close());
    assert.equal(await win.evaluate(w=>w.isVisible()),true);
    const options=await app.evaluate(({dialog})=>dialog.__lastCloseOptions);
    assert.deepEqual(options.buttons,['關閉程式','背景執行','取消']);
    assert.equal(options.cancelId,2);
    await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:1});});
    await win.evaluate(w=>w.close());
    assert.equal(await win.evaluate(w=>w.isVisible()),false);
    assert.equal((await fetch('http://127.0.0.1:49180/game')).status,200);
    await win.evaluate(w=>w.show());
    await app.evaluate(({clipboard},text)=>clipboard.writeText(text),original);
    await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:0});});
    const closed=app.waitForEvent('close');
    await win.evaluate(w=>w.close());
    await closed;
    await assert.rejects(fetch('http://127.0.0.1:49180/game'));
    console.log('PASS: mode-first setup/back preserves entries; visible back buttons; single/local/remote/create/join flow; exact native clipboard for both links despite browser denial; X cancel/background/quit paths preserve or stop hosting correctly.');
  } finally {
    if(original!==undefined) await app.evaluate(({clipboard},text)=>clipboard.writeText(text),original).catch(()=>{});
    await app.close().catch(()=>{});
  }
})().catch(e=>{console.error(e);process.exitCode=1;});
